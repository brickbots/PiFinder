#!/usr/bin/env python3
"""Build astro_data/satellite_std_mags.csv from the CelesTrak SATCAT.

The standard magnitude of a satellite is its brightness at 1000 km range and
90 degrees phase angle. Few objects have a measured value, so this script
estimates it from the radar cross section (RCS) in the SATCAT:

    std_mag = 5.5 - 2.5 * log10(RCS in m^2)

The constant puts the ISS (RCS about 400 m^2) near -1 and the HST (RCS about
28 m^2) near +2, close to their observed standard magnitudes. Only objects in
Earth orbit with an RCS of at least 1 m^2 are kept, so the file stays small.

Usage: gen_satellite_mags.py [satcat.csv] [output.csv]
"""

import csv
import io
import math
import sys
from pathlib import Path

import requests

SATCAT_URL = "https://celestrak.org/pub/satcat.csv"
MIN_RCS_M2 = 1.0
RCS_MAG_ZERO = 5.5

# Observed standard magnitudes. They replace the RCS estimate.
MEASURED_STD_MAGS = {
    25544: -1.3,  # ISS
    20580: 2.2,  # HST
}


def rcs_to_std_mag(rcs_m2: float) -> float:
    return RCS_MAG_ZERO - 2.5 * math.log10(rcs_m2)


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    output = (
        Path(sys.argv[2])
        if len(sys.argv) > 2
        else root / "astro_data" / "satellite_std_mags.csv"
    )
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text()
    else:
        response = requests.get(SATCAT_URL, timeout=60)
        response.raise_for_status()
        text = response.text

    rows = []
    for row in csv.DictReader(io.StringIO(text)):
        if row["DECAY_DATE"] or row["ORBIT_CENTER"] != "EA" or not row["RCS"]:
            continue
        rcs = float(row["RCS"])
        if rcs < MIN_RCS_M2:
            continue
        norad = int(row["NORAD_CAT_ID"])
        mag = MEASURED_STD_MAGS.get(norad, rcs_to_std_mag(rcs))
        rows.append((norad, round(mag, 1)))
    for norad, mag in MEASURED_STD_MAGS.items():
        if norad not in {r[0] for r in rows}:
            rows.append((norad, mag))
    rows.sort()

    with output.open("w") as out:
        out.write("# NORAD id, standard magnitude (1000 km, 90 deg phase)\n")
        out.write("# Generated by python/scripts/gen_satellite_mags.py\n")
        for norad, mag in rows:
            out.write(f"{norad},{mag}\n")
    print(f"wrote {len(rows)} magnitudes to {output}")


if __name__ == "__main__":
    main()
